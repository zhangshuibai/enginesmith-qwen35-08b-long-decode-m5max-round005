#!/usr/bin/env python3
"""Flatten the vendored MLX NAX helper and append the engine Q4 entry point."""
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
VENDOR = ROOT / "third_party/linear_mlx"
seen = set()


def expand(path):
    path = path.resolve()
    if path in seen:
        return ""
    seen.add(path)
    text = path.read_text()
    text = re.sub(r'^#pragma once\s*$', '', text, flags=re.M)
    def replace(match):
        return expand(VENDOR / match.group(1))
    return re.sub(r'^#include "mlx/backend/metal/kernels/([^\"]+)"\s*$', replace, text, flags=re.M)


header = """// Generated by tools/gen_linear_nax.py; edit its inputs, not this file.
// MLX 0.32.4 NAX matrix tile helpers, Copyright (c) 2024-2025 Apple Inc.
// MIT license: third_party/linear_mlx/LICENSE.
#include <metal_stdlib>
"""
source = header + expand(VENDOR / 'steel/gemm/nax.h')
source += '\n' + (ROOT / 'tools/linear_nax_body.metal').read_text()
(ROOT / 'src/kernels/linear_nax.metal').write_text(source)
