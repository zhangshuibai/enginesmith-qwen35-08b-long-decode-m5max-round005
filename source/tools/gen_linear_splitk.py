#!/usr/bin/env python3
"""Flatten the MLX 0.32.4 simdgroup-matrix tiles used by split-K QMM."""
from pathlib import Path
import re

ROOT=Path(__file__).resolve().parents[1]
VENDOR=ROOT/'third_party/linear_mlx'
seen=set()

def expand(path):
    path=path.resolve()
    if path in seen:return ''
    seen.add(path)
    text=path.read_text()
    if path.name=='mma.h':
        # Complex matrices are irrelevant to this checkpoint. Remove only
        # their two explicit specializations, retaining generic tiles intact.
        start=text.index('template <typename InT>\nstruct TransformNone<complex64_t')
        end=text.index('\ntemplate <',start+10)
        text=text[:start]+text[end:]
        start=text.index('template <\n    typename U,\n    int BM,')
        text=text[:start]+'\n} // namespace steel\n} // namespace mlx\n'
    text=re.sub(r'^#pragma once\s*$','',text,flags=re.M)
    return re.sub(r'^#include "mlx/backend/metal/kernels/([^\"]+)"\s*$',lambda m:expand(VENDOR/m.group(1)),text,flags=re.M)

header='''// Generated by tools/gen_linear_splitk.py; edit its inputs.
// MLX 0.32.4, Copyright (c) 2024 Apple Inc.
// MIT license: third_party/linear_mlx/LICENSE.
#include <metal_stdlib>
using namespace metal;
'''
source=header+expand(VENDOR/'steel/gemm/mma.h')
source+='\n'+(ROOT/'tools/linear_splitk_body.metal').read_text()
(ROOT/'src/kernels/linear_splitk.metal').write_text(source)
